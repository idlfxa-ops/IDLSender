  const bounces = isDraftOrSched ? 0 : Math.round((sent * c.bouncePct) / 100);
  const delivered = isDraftOrSched ? 0 : Math.max(0, sent - bounces);
  const opened = isDraftOrSched ? 0 : Math.round((delivered * c.openPct) / 100);
  const clicked = isDraftOrSched ? 0 : Math.round((opened * c.clickPct) / 100);
  const unsubscribed = isDraftOrSched ? 0 : c.unsubCount;

